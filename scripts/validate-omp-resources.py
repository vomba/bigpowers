#!/usr/bin/env python3
"""Validate native generated resources; --tracked also checks Git delivery. story: e82s03"""
from __future__ import annotations

import importlib.util
from pathlib import Path
import re
import subprocess
import sys

sys.dont_write_bytecode = True
SPEC = importlib.util.spec_from_file_location("skill_renderer", Path(__file__).parent / "lib/srp-engine.py")
RENDERER = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(RENDERER)
MARKER_PREFIX = "# Generated by scripts/sync-skills.sh from skills/"


def require_regular(path: Path) -> None:
    """Reject destination links before reading files, including dangling links."""
    for ancestor in (path, *path.parents):
        if ancestor.is_symlink():
            raise ValueError(f"Symlink destination/ancestor {ancestor}; preserve it and use a regular generated tree")
    if not path.is_file():
        raise ValueError(f"Missing/invalid native resource {path}; regenerate with scripts/sync-skills.sh")


def read_generated(path: Path, name: str) -> tuple[dict, str]:
    """Read a marked native artifact through the canonical frontmatter parser."""
    require_regular(path)
    text = path.read_text(encoding="utf-8")
    lines = text.splitlines()
    marker = f"{MARKER_PREFIX}{name}/SKILL.md"
    if len(lines) < 2 or lines[0] != "---" or lines[1] != marker:
        raise ValueError(f"Unmarked native artifact {path}; preserve authored files and regenerate")
    return RENDERER.parse_frontmatter(text, path)


def validate(root: Path, tracked: bool = False) -> None:
    """Validate the catalogue without generating files or requiring the OMP SDK."""
    expected: set[str] = set()
    names: set[str] = set()
    for source in RENDERER.iterate_skills(str(root)):
        item = RENDERER.parse_skill(source)
        name = item["name"]
        if not re.fullmatch(r"[a-z][a-z0-9-]*", name) or name in names:
            raise ValueError(f"Unsafe/duplicate source skill {name!r}; repair the canonical catalogue")
        names.add(name)
        skill = root / ".omp/skills" / name / "SKILL.md"
        metadata, _ = read_generated(skill, name)
        controls = item["invocation_controls"]
        required = {"name": name, "description": item["description"], **controls}
        if metadata != required or any(type(value) is not bool for value in controls.values()):
            raise ValueError(f"Invalid native metadata {skill}; regenerate from its source")
        command = root / ".omp/commands" / f"bigpowers-{name}.md"
        command_metadata, body = read_generated(command, name)
        if command_metadata != {"description": item["description"]} or f"skill://{name}" not in body:
            raise ValueError(f"Invalid native command {command}; regenerate from its source")
        expected.update(str(path.relative_to(root)) for path in (skill, command))
    if not names:
        raise ValueError(f"No canonical skills in {root / 'skills'}; use the package/repository root")
    actual = list((root / ".omp/skills").glob("*/SKILL.md"))
    actual += list((root / ".omp/commands").glob("bigpowers-*.md"))
    for path in actual:
        relative = str(path.relative_to(root))
        if relative in expected or path.is_symlink() or path.parent.is_symlink() or not path.is_file():
            continue
        with path.open(encoding="utf-8", errors="replace") as stream:
            stream.readline()
            marker = stream.readline()
        if marker.startswith(MARKER_PREFIX):
            raise ValueError(f"Stale generated artifact {path}; review and remove the obsolete generated file")
    if tracked:
        result = subprocess.run(["git", "ls-files", "-z", "--", ".omp"], cwd=root,
                                check=True, capture_output=True, text=True)
        missing = expected - set(result.stdout.split("\0"))
        if missing:
            raise ValueError(f"Untracked native artifacts: {', '.join(sorted(missing))}; include generated output in the change")
    print(f"OMP native resources valid: {len(names)} skills and commands")


def main() -> int:
    if len(sys.argv) not in (2, 3) or (len(sys.argv) == 3 and sys.argv[2] != "--tracked"):
        print("Usage: validate-omp-resources.py ROOT [--tracked]", file=sys.stderr)
        return 2
    try:
        validate(Path(sys.argv[1]).resolve(), len(sys.argv) == 3)
    except (OSError, ValueError, subprocess.CalledProcessError) as error:
        print(f"OMP validation failed: {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
