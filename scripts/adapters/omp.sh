#!/usr/bin/env bash
# story: e37s10 e82s03

omp_refuse() {
  printf 'omp: %s; preserve authored files and regenerate from skills/\n' "$1" >&2
  return 1
}

omp_non_directory_ancestor() {
  [[ "$1" != "$2" && -e "$1" && ! -d "$1" ]]
}

omp_assert_target() {
  local path="$1" marker="$2" parent first second
  parent="$path"
  while [[ "$parent" != / && "$parent" != . ]]; do
    [[ ! -L "$parent" ]] || { omp_refuse "symlink destination/ancestor $parent"; return 1; }
    if omp_non_directory_ancestor "$parent" "$path"; then
      omp_refuse "non-directory ancestor $parent"; return 1
    fi
    parent="$(dirname "$parent")"
  done
  [[ -e "$path" ]] || return 0
  [[ -f "$path" ]] || { omp_refuse "non-regular destination $path"; return 1; }
  { IFS= read -r first; IFS= read -r second; } < "$path"
  [[ "$first" == --- && "$second" == "$marker" ]] || {
    omp_refuse "unmarked destination $path"; return 1;
  }
}

omp_header() {
  "${PYTHON:-python3}" -c '
import json, sys
name, description, raw = sys.argv[1:]
controls = json.loads(raw)
if not description.strip() or not isinstance(controls, dict) or any(
    key not in ("hide", "disable-model-invocation") or type(value) is not bool
    for key, value in controls.items()
):
    sys.exit("Invalid OMP description/controls; use a nonempty description and boolean invocation controls")
for key, value in {"description": description, "name": name, **controls}.items():
    print(key + ": " + json.dumps(value, ensure_ascii=False))
' "$IR_NAME" "${IR_DESCRIPTION-}" "$1"
}

omp_write_skill() {
  local file="$1" marker="$2" header="$3"
  {
    printf '%s\n' '---' "$marker" "$header"
    printf '%s\n\n' '---'
    cat <<'POLICY'
## Native OMP execution

Keep small work inline. These instructions do not switch the parent model or
permit delegation. When useful delegation is allowed by the active tool contract
and parent policy, use existing agents by responsibility: an implementation-capable
task agent for implementation, reviewer for independent review, security-reviewer
for delegated security analysis, and scout for warranted repository exploration.
Omit the implementation agent selector only when the actual default resolves to
task; select it explicitly only when the exposed contract permits that choice.
Otherwise report the boundary, without substituting an agent or changing settings.
Preserve workflow stages, acceptance criteria, and review independence/count.
Existing agent allocations, task.agentModelOverrides and modelRoles select worker
models/providers. Do not override them or translate source model-tier examples.
Respect the active user's and project's policies and authorization boundaries.

POLICY
    printf '[Canonical skill resources](../../../skills/%s/) are relative to this file.\n' "$IR_NAME"
    printf '%s\n\n' 'Inspect that source directory for supporting filenames; do not traverse skill:// or reinterpret project-relative workflow commands as skill-owned paths.'
    printf '%s\n' "${IR_BODY_SKILL:-${IR_BODY:-}}"
  } > "$file"
}

render_skill() {
  source "$(dirname "${BASH_SOURCE[0]}")/../lib/adapter-guard.sh"
  bp_assert_safe_skill_name "${IR_NAME-}" omp >/dev/null || return 1
  local root skills commands skill command marker header controls
  root="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd -P)" || return 1
  skills="${OMP_SKILLS:-$root/.omp/skills}"
  commands="${OMP_COMMANDS:-$(dirname "$skills")/commands}"
  skill="$skills/$IR_NAME/SKILL.md"
  command="$commands/bigpowers-$IR_NAME.md"
  marker="# Generated by scripts/sync-skills.sh from skills/$IR_NAME/SKILL.md"
  controls="${IR_INVOCATION_CONTROLS-}"
  [[ -n "$controls" ]] || controls='{}'
  header=$(omp_header "$controls") || return 1
  omp_assert_target "$skill" "$marker" && omp_assert_target "$command" "$marker" || return 1
  mkdir -p "$skills/$IR_NAME" "$commands" || return 1
  omp_write_skill "$skill" "$marker" "$header" || return 1
  {
    printf '%s\n' '---' "$marker" "${header%%$'\n'*}" '---'
    printf '\nRead skill://%s and follow its workflow using the existing native agent allocations.\n\n' "$IR_NAME"
    printf '%s\n' "\$ARGUMENTS"
  } > "$command"
}

if [[ ! -t 0 ]]; then
  JSON_INPUT=$(cat)
  if [[ -n "$JSON_INPUT" ]]; then
    if ! {
      IFS= read -r -d '' IR_NAME &&
      IFS= read -r -d '' IR_DESCRIPTION &&
      IFS= read -r -d '' IR_BODY &&
      IFS= read -r -d '' IR_BODY_SKILL &&
      IFS= read -r -d '' IR_INVOCATION_CONTROLS
    } < <(printf '%s' "$JSON_INPUT" | "${PYTHON:-python3}" -c '
import json, sys
item = json.load(sys.stdin)
for value in (item["name"], item["description"], item["body"],
              item.get("body_pi_skill", item["body"]), json.dumps(item.get("invocation_controls", {}))):
    if not isinstance(value, str) or "\0" in value:
        sys.exit("Invalid OMP IR string; regenerate through srp-engine.py")
    sys.stdout.write(value + "\0")
'); then
      exit 1
    fi
    render_skill
  fi
fi
